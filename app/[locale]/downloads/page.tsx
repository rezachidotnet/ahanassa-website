import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { BookOpen, Download, FileSpreadsheet, FileText, Ruler } from "lucide-react";
import { isLocale, locales, localizedPath, type Locale } from "@/config/locales";
import { buildPageMetadata } from "@/lib/metadata/resolve";
import { publicPageIndexable } from "@/lib/seo/indexing-policy";
import { DOWNLOADS_ROUTE, drawingPath, rawMaterialsCatalogPath, sectionsCatalogPath, specSheetPath } from "@/lib/downloads/paths";
import { downloadsCopy } from "@/lib/downloads/copy";
import { loadDownloadCatalog } from "@/lib/downloads/source";
import { catalogChapters, planDrawings, summarizeSkipped } from "@/lib/downloads/model";
import { ITEM_LIST_TEMPLATE_PATH } from "@/lib/rfq/attachment-policy";
import { PageHero } from "@/components/ui/page-hero";
import { cardVariants } from "@/components/ui/surface-variants";

interface PageProps {
  params: Promise<{ locale: string }>;
}

export { generateLocaleStaticParams as generateStaticParams } from "@/lib/static/locale-params";

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { locale } = await params;
  if (!isLocale(locale)) return {};
  const t = downloadsCopy(locale);
  return buildPageMetadata({ locale, path: DOWNLOADS_ROUTE, title: t.title, description: t.description, indexable: publicPageIndexable() });
}

const FILE_LINK = "text-navy hover:text-copper inline-flex min-h-11 items-center gap-2 text-sm font-semibold underline decoration-1 underline-offset-4 hover:decoration-2";
const SECTION = "border-border border-b section-y";

function SectionTitle({ id, icon: Icon, title, body }: { id: string; icon: typeof Ruler; title: string; body: string }) {
  return (
    <div className="max-w-3xl">
      <h2 id={id} className="text-navy flex items-center gap-3 text-2xl font-extrabold">
        <Icon aria-hidden="true" className="text-copper size-6 shrink-0" />
        {title}
      </h2>
      <p className="text-muted-foreground mt-3 leading-relaxed">{body}</p>
    </div>
  );
}

/**
 * W17.2 — Download Center (fa/en/ar): section drawings (DXF + SVG preview), one spec sheet per product family,
 * the two catalogs and the item-list template. Every file is generated by the static build from the same
 * catalog snapshot (lib/downloads/generate.ts); this page lists exactly what that step writes. No price.
 */
export default async function DownloadsPage({ params }: PageProps) {
  const { locale: rawLocale } = await params;
  if (!isLocale(rawLocale)) notFound();
  const locale: Locale = rawLocale;
  const t = downloadsCopy(locale);
  const catalog = await loadDownloadCatalog(locale);
  const chapters = catalogChapters(catalog);
  const categoryName = new Map(catalog.categories.map((c) => [c.code, c.name]));
  const drawings = planDrawings(catalog);
  const pending = [...new Set(summarizeSkipped(drawings.skipped).map((g) => categoryName.get(g.categoryCode)).filter((n): n is string => Boolean(n)))];
  const drawingGroups = chapters.map((c) => ({ ...c, drawings: drawings.drawn.filter((d) => d.categoryCode === c.code) })).filter((c) => c.drawings.length);
  const others = locales.filter((l) => l !== locale);
  const listSep = locale === "en" ? ", " : "، ";

  return (
    <>
      <PageHero locale={locale} eyebrow={t.h1} title={t.h1} body={t.intro} breadcrumb={[{ path: DOWNLOADS_ROUTE, label: t.h1 }]} />

      <section id="drawings" aria-labelledby="drawings-title" className={`bg-background ${SECTION}`}>
        <div className="container-x">
          <SectionTitle id="drawings-title" icon={Ruler} title={t.drawings.title} body={t.drawings.body} />
          {drawingGroups.length === 0 && <p className="text-muted-foreground mt-6 text-sm">{t.drawings.empty}</p>}
          {drawingGroups.map((group) => (
            <div key={group.code} className="mt-10">
              <h3 className="text-navy text-lg font-bold">{group.name}</h3>
              <ul className="mt-4 grid grid-cols-2 gap-4 sm:grid-cols-3 lg:grid-cols-4">
                {group.drawings.map((d) => (
                  <li key={d.slug} className={cardVariants({ variant: "panel" })}>
                    {/* The SVG preview is a static file drawn from the same geometry as the DXF. */}
                    <img src={drawingPath(d.slug, "svg")} alt={t.drawings.previewAlt(d.title)} width={240} height={240} loading="lazy" decoding="async" className="aspect-square w-full bg-white object-contain" />
                    <p dir="ltr" className="text-navy mt-3 text-sm font-bold">
                      {d.title}
                    </p>
                    <div className="mt-1 flex flex-wrap gap-x-4">
                      <a href={drawingPath(d.slug, "dxf")} download className={FILE_LINK}>
                        <Download aria-hidden="true" className="size-4" />
                        {t.drawings.dxf}
                      </a>
                      <a href={drawingPath(d.slug, "svg")} className={FILE_LINK}>
                        {t.drawings.svg}
                      </a>
                    </div>
                  </li>
                ))}
              </ul>
            </div>
          ))}
          {pending.length > 0 && (
            <p className="text-muted-foreground mt-8 max-w-3xl text-sm leading-relaxed">
              {t.drawings.pending} {pending.join(listSep)}
            </p>
          )}
        </div>
      </section>

      <section id="spec-sheets" aria-labelledby="spec-sheets-title" className={`bg-muted/40 ${SECTION}`}>
        <div className="container-x">
          <SectionTitle id="spec-sheets-title" icon={FileText} title={t.specSheets.title} body={t.specSheets.body} />
          <ul className="mt-8 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
            {catalog.categories.map((c) => (
              <li key={c.code} className={cardVariants({ variant: "panel" })}>
                <a href={specSheetPath(c.segment, locale)} className={FILE_LINK}>
                  <FileText aria-hidden="true" className="text-copper size-4 shrink-0" />
                  {c.name} <span className="text-muted-foreground font-normal">({t.specSheets.pdf})</span>
                </a>
              </li>
            ))}
          </ul>
        </div>
      </section>

      <section id="catalogs" aria-labelledby="catalogs-title" className={`bg-background ${SECTION}`}>
        <div className="container-x">
          <SectionTitle id="catalogs-title" icon={BookOpen} title={t.catalogs.title} body={t.catalogs.body} />
          <div className="mt-8 grid gap-6 md:grid-cols-2">
            {[
              { title: t.catalogs.sections, body: t.catalogs.sectionsBody, href: sectionsCatalogPath },
              { title: t.catalogs.raw, body: t.catalogs.rawBody, href: rawMaterialsCatalogPath },
            ].map((c) => (
              <div key={c.title} className={cardVariants({ variant: "panel" })}>
                <h3 className="text-navy text-lg font-bold">{c.title}</h3>
                <p className="text-muted-foreground mt-2 text-sm leading-relaxed">{c.body}</p>
                <a href={c.href(locale)} className={`${FILE_LINK} mt-3`}>
                  <Download aria-hidden="true" className="size-4" />
                  PDF · {t.languageNames[locale]}
                </a>
                <p className="text-muted-foreground mt-1 flex flex-wrap items-center gap-x-4 text-sm">
                  {t.catalogs.otherLanguages}
                  {others.map((l) => (
                    <a key={l} href={c.href(l)} hrefLang={l} lang={l} className={FILE_LINK}>
                      {t.languageNames[l]}
                    </a>
                  ))}
                </p>
              </div>
            ))}
          </div>
        </div>
      </section>

      <section id="templates" aria-labelledby="templates-title" className="bg-muted/40 section-y">
        <div className="container-x">
          <SectionTitle id="templates-title" icon={FileSpreadsheet} title={t.templates.title} body={t.templates.itemListBody} />
          <a href={ITEM_LIST_TEMPLATE_PATH(locale)} download className={`${FILE_LINK} mt-6`}>
            <FileSpreadsheet aria-hidden="true" className="text-copper size-4" />
            {t.templates.itemList}
          </a>
          <p className="mt-2">
            <a href={localizedPath(locale, "/contact")} className={FILE_LINK}>
              {t.pdf.request}
            </a>
          </p>
        </div>
      </section>
    </>
  );
}
