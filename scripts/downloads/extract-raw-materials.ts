/**
 * W17.2 — regenerates lib/downloads/raw-materials-data.ts from the private Odoo repository's catalog data,
 * read-only:
 *
 *   node scripts/downloads/extract-raw-materials.ts <ahanassa-odoo>/addons/ahanassa_catalog_flat_raw/data/flat_raw_catalog.json
 *
 * Raw materials are not in the public catalog snapshot yet (W9.8: RFQ only, draft templates), so the
 * raw-materials catalog PDF reads this extract. It copies ONLY the public fields of the raw-material
 * templates (lines BILLET, DRI, IRON_ORE): names, public descriptions, standard and grade codes. Never the
 * internal note, SKUs, price mode, or the variant specification classes — Odoo marks those classes as
 * defaults "to be confirmed by sourcing before publishing", so the catalog says "specifications on request".
 */
import fs from "node:fs";
import path from "node:path";

const RAW_LINES = new Set(["BILLET", "DRI", "IRON_ORE"]);
const source = process.argv[2];
if (!source) {
  console.error("usage: extract-raw-materials.ts <flat_raw_catalog.json>");
  process.exit(2);
}
interface Localized { fa: string; en: string; ar: string }
interface Template { key: string; line: string; form_code: string; grade_code: string; standard_code: string; names: Localized; public_description: Localized }
const data = JSON.parse(fs.readFileSync(source, "utf8")) as { templates: Template[]; standards: Array<{ code: string } & Localized> };
const standards = new Map(data.standards.map((s) => [s.code, s]));
const rows = data.templates
  .filter((t) => RAW_LINES.has(t.line))
  .map((t) => ({
    key: t.key,
    line: t.line,
    formCode: t.form_code,
    grade: t.grade_code || null,
    standard: t.standard_code ? (standards.get(t.standard_code)?.en ?? t.standard_code) : null,
    name: { fa: t.names.fa, en: t.names.en, ar: t.names.ar },
    description: { fa: t.public_description.fa, en: t.public_description.en, ar: t.public_description.ar },
  }));
const out = path.resolve(import.meta.dirname, "../../lib/downloads/raw-materials-data.ts");
fs.writeFileSync(
  out,
  `/**
 * GENERATED by scripts/downloads/extract-raw-materials.ts — do not edit by hand.
 * Source: ahanassa-odoo addons/ahanassa_catalog_flat_raw/data/flat_raw_catalog.json (W9.8), public fields only.
 */
import type { RawMaterialTemplate } from "./raw-materials.ts";

export const RAW_MATERIAL_TEMPLATES: readonly RawMaterialTemplate[] = ${JSON.stringify(rows, null, 2)};
`,
);
console.log(`wrote ${rows.length} raw-material templates to ${path.relative(process.cwd(), out)}`);
