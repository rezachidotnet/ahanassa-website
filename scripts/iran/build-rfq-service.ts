/**
 * W32 (W29 P2 §7, owner rule): the domestic RFQ intake as ONE file — `rfq-ir.mjs` — built in CI from the same
 * code_sha as the static artifact and shipped INSIDE the signed domestic bundle (scripts/iran/bundle.ts → rfq/), so
 * the server runs exactly the RFQ Worker's own modules with no npm, no node_modules and no repository checkout.
 *
 *   node scripts/iran/build-rfq-service.ts <out file>
 *
 * esbuild (pinned devDependency), platform node, target node24, ESM, not minified (readable on the server), with the
 * D1 / public / IR migrations embedded via `define` (lib/rfq-node/migrations.ts). The output is deterministic: the same
 * sources and esbuild version give the same bytes, so the bundle's sha256 is stable across rebuilds of one commit.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { buildSync } from "esbuild";
import { loadMigrations } from "../../lib/rfq-node/migrations.ts";

const ROOT = path.resolve(import.meta.dirname, "../..");
export const RFQ_SERVICE_FILE = "rfq-ir.mjs";
export const RFQ_SERVICE_ENTRY = path.join(ROOT, "services/rfq-ir/main.ts");

export function buildRfqService(outFile: string): { bytes: number; sha256: string } {
  const banner = [
    "// ahanassa domestic RFQ intake (W32) — generated by scripts/iran/build-rfq-service.ts; do not edit.",
    'import { createRequire as __ahanassaCreateRequire } from "node:module";',
    "const require = __ahanassaCreateRequire(import.meta.url);",
  ].join("\n");
  const result = buildSync({
    entryPoints: [RFQ_SERVICE_ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    platform: "node",
    target: "node24",
    format: "esm",
    outfile: outFile,
    write: false,
    minify: false,
    legalComments: "none",
    sourcemap: false,
    charset: "utf8",
    banner: { js: banner },
    define: { __RFQ_IR_MIGRATIONS__: JSON.stringify(loadMigrations()) },
    logLevel: "silent",
  });
  if (result.errors.length) throw new Error(`build-rfq-service: ${result.errors.map((e) => e.text).join("; ")}`);
  const code = Buffer.from(result.outputFiles[0].contents);
  // A bundle must never carry a test hook: the staging test routes and the Turnstile test path live only in
  // workers/rfq/index.staging.ts, which the service never imports (lib/rfq-worker/bundle-scan.test.ts, same rule).
  for (const marker of ["stagingTestRoutes", "stagingTurnstileTestPath", "stagingTurnstileExtractTestPath"]) if (code.includes(marker)) throw new Error(`build-rfq-service: test code in the bundle (${marker})`);
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, code);
  return { bytes: code.length, sha256: crypto.createHash("sha256").update(code).digest("hex") };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = process.argv[2];
  if (!out) {
    console.error("usage: build-rfq-service.ts <out file>");
    process.exit(2);
  }
  const r = buildRfqService(path.resolve(out));
  console.log(`[iran] ${RFQ_SERVICE_FILE}: ${r.bytes} B, sha256 ${r.sha256}`);
}
